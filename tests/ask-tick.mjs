import { execSync } from 'child_process';
import { chromium, BASE, exe, shots } from './_env.mjs';
const b = await chromium.launch({ ...exe });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${BASE}/?theme=term#r=claude-zz-q`, { waitUntil: 'domcontentloaded' });
await p.waitForSelector('.card.ask', { timeout: 20000 }); await p.waitForTimeout(800);
const typ = () => p.evaluate(() => { const t = document.querySelector('[data-type]'); return t ? (t.classList.contains('on') ? 'ticked ' : 'not ticked ') + t.innerText.trim() : 'none'; });
const term = () => execSync("tmux capture-pane -p -t claude-zz-q | grep -E '^\\s*(❯\\s*)?4\\.' | head -1").toString().trim();
await p.click('.opt:has-text("Apple")'); await p.click('[data-go]'); await p.waitForTimeout(1500);
console.log('Q:', await p.evaluate(() => document.querySelector('.qn')?.textContent));
await p.click('[data-type]'); await p.type('.typed input', 'purple');
console.log('while typing:', await typ(), '| terminal:', term());
await p.click('.opt:has-text("Red")'); await p.waitForTimeout(1500);
console.log('after ticking Red:', await typ(), '| input:', await p.inputValue('.typed input'));
await p.click('[data-back]'); await p.waitForTimeout(1500);
console.log('after Back, terminal row:', term());
await p.click('[data-go]'); await p.waitForTimeout(1500);
console.log('forward again:', await typ());
await p.click('[data-go]'); await p.waitForTimeout(1500);
console.log('review:', (await p.evaluate(() => document.querySelector('#cards .body')?.innerText)).replace(/\n/g, ' / '));
await p.screenshot({ path: `${shots('ask2')}/390-review.png` });
console.log('errors', errs); await b.close();
