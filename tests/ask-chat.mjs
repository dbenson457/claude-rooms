import { execSync } from 'child_process';
import { chromium, BASE, exe, shots } from './_env.mjs';
const OUT = shots('ask2'), W = 390;
const b = await chromium.launch({ ...exe });
const p = await (await b.newContext({ viewport: { width: W, height: 844 }, hasTouch: true, isMobile: true })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${BASE}/?theme=term#r=claude-zz-q`, { waitUntil: 'domcontentloaded' });
await p.waitForSelector('.card.ask', { timeout: 20000 }); await p.waitForTimeout(800);
const ov = () => p.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await p.screenshot({ path: `${OUT}/390-fruit.png` });
await p.click('[data-type]'); await p.fill('.typed input', 'mango'); await p.screenshot({ path: `${OUT}/390-typing.png` });
await p.click('[data-go]'); await p.waitForTimeout(1500);
console.log('after typed Next:', await p.evaluate(() => document.querySelector('.qtab.cur')?.textContent), 'overflow', await ov());
await p.screenshot({ path: `${OUT}/390-colours.png` });
await p.click('[data-chat]'); await p.waitForTimeout(10000);
console.log('card gone:', !(await p.$('#cards .card')), 'composer focused:', await p.evaluate(() => document.activeElement?.id));
console.log('reply:', execSync("tmux capture-pane -p -t claude-zz-q | grep '●' | tail -1").toString().trim().slice(0, 220));
console.log('errors', errs);
await b.close();
