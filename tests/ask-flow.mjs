import { execSync } from 'child_process';
import { chromium, BASE, exe, shots } from './_env.mjs';
const OUT = shots('ask2'), W = Number(process.argv[2] || 1280);
const b = await chromium.launch({ ...exe });
const p = await (await b.newContext({ viewport: { width: W, height: W < 500 ? 844 : 800 } })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(`${BASE}/?theme=term#r=claude-zz-q`, { waitUntil: 'domcontentloaded' });
await p.waitForSelector('.card.ask', { timeout: 20000 }); await p.waitForTimeout(800);
const st = async (tag) => { await p.waitForTimeout(1300); const s = await p.evaluate(() => { const c = document.querySelector('#cards .card'); if (!c) return 'no card'; return { tabs: [...c.querySelectorAll('.qtab')].map((t) => (t.classList.contains('cur') ? '*' : '') + t.textContent.trim()).join(' '), q: c.querySelector('.qq')?.textContent || c.querySelector('.body')?.innerText.slice(0, 80), opts: [...c.querySelectorAll('.opt')].map((o) => (o.classList.contains('sel') ? '>' : '') + o.innerText.split('\n')[0]).join(' | '), go: c.querySelector('[data-go]') ? (c.querySelector('[data-go]').disabled ? 'go:off' : 'go:on') : '' }; }); console.log(tag.padEnd(26), JSON.stringify(s)); await p.screenshot({ path: `${OUT}/${W}-${tag.replace(/\W+/g, '_')}.png` }); };
const term = () => execSync("tmux capture-pane -p -t claude-zz-q | grep -E '^←|❯|\\[' | head -3").toString().trim().split('\n')[0];
await st('start');
await p.click('.qtab:has-text("Fruit")'); await st('tap Fruit tab');
await p.click('.opt:has-text("Pear")'); await st('tap Pear (not sent)'); console.log('   terminal:', term());
await p.click('[data-go]'); await st('Next');
await p.click('.opt:has-text("Red")'); await st('tick Red');
await p.click('[data-type]'); await p.fill('.typed input', 'teal'); await p.click('.typed button'); await st('type teal + Save');
await p.click('[data-back]'); await st('Back');
await p.click('[data-go]'); await st('Next (Pear kept)');
await p.click('[data-go]'); await st('Next to review');
await p.click('[data-back]'); await st('Back from review');
await p.click('[data-go]'); await st('Next to review again');
await p.click('.opt:has-text("Submit answers")'); await p.waitForTimeout(9000);
console.log('reply:', execSync("tmux capture-pane -p -t claude-zz-q | grep '●' | tail -1").toString().trim().slice(0, 200));
console.log('errors', errs);
await b.close();
